    function openProfileSection(sectionName, button) {
        const sectionWindows = document.getElementById('sectionWindows');
        const selectedPanel = document.getElementById(sectionName + '-panel');

        sectionWindows.querySelectorAll('.section-card').forEach(function(panel) {
            panel.classList.remove('is-open');
        });

        document.querySelectorAll('.section-button').forEach(function(sectionButton) {
            sectionButton.classList.remove('is-active');
        });

        if (!selectedPanel) return;

        selectedPanel.classList.add('is-open');
        sectionWindows.classList.add('is-open');
        sectionWindows.scrollTop = 0;
        if (button) button.classList.add('is-active');
        document.body.classList.add('profile-window-open');
    }

    function closeProfileSection() {
        const sectionWindows = document.getElementById('sectionWindows');
        sectionWindows.classList.remove('is-open');
        sectionWindows.querySelectorAll('.section-card').forEach(function(panel) {
            panel.classList.remove('is-open');
        });
        document.body.classList.remove('profile-window-open');
    }

    document.addEventListener('keydown', function(event) {
        if (event.key === 'Escape') {
            closeProfileSection();
        }
    });

    let currentInboxId = null;

    let currentPartner = "";

    const messageInput =
        document.getElementById("inbox_input");

    messageInput.addEventListener(
