    function openInbox(item, partner) {

        currentInboxId = item.item_id;

        currentPartner = partner;

        const profileLink = `
        <a
            href="other_profile.php?user=${partner}"
            style="
                text-decoration:none;
                font-size:12px;
                color:var(--primary);
                margin-left:10px;
                font-weight:normal;
            "
        >
            (View Profile)
        </a>
        `;

        document.getElementById(
            'inbox_title'
        ).innerHTML =
            item.title +
            " (@" +
            partner +
            ")" +
            profileLink;

        fetchInbox();

        document.getElementById(
            'inboxModal'
        ).style.display = 'flex';
    }

    function fetchInbox() {

        if(!currentInboxId) return;

        const fd = new FormData();

        fd.append('fetch_msgs', '1');

        fd.append('item_id', currentInboxId);

        fd.append('target_user', currentPartner);

        fetch(
            '../index.php',
            {
                method: 'POST',
                body: fd
            }
        )

        .then(r => r.json())

        .then(data => {

            const box =
                document.getElementById('inbox_msgs');

            box.innerHTML = "";

            data.forEach(m => {

                const isMe =
                    m.sender === "<?php echo $me; ?>";

                box.innerHTML += `
                <div class="
                    msg-bubble
                    ${isMe ? 'msg-me' : 'msg-them'}
                ">

                    <small style="
                        opacity:0.6;
                        display:block;
                        font-size:10px;
                    ">
                        @${m.sender}
                    </small>

                    ${m.message}

                </div>
                `;

            });

            box.scrollTop = box.scrollHeight;

        });

    }

    function sendInboxMsg() {

        const txt =
            document.getElementById(
                'inbox_input'
            ).value;

        if(!txt || !currentPartner) return;

        const fd = new FormData();

        fd.append('send_msg', '1');

        fd.append('item_id', currentInboxId);

        fd.append('message', txt);

        fd.append('target_user', currentPartner);

        fetch(
            '../index.php',
            {
                method: 'POST',
                body: fd
            }
        )

        .then(() => {

            document.getElementById(
                'inbox_input'
            ).value = "";

            fetchInbox();

        });

    }

    function encodeImage(input) {

        document.getElementById('remove_profile_image').value = '0';
        document.getElementById('profile-image-status').textContent =
            'New image selected';

        if (input.files && input.files[0]) {

            const reader = new FileReader();

            reader.onload = function(e) {

                document.getElementById(
                    'pic_base64'
                ).value = e.target.result;

            }

            reader.readAsDataURL(input.files[0]);

        }

    }

