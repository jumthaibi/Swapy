    // A post can be referenced by chats and delivery requests. Delete those
    // dependent rows in one transaction before deleting the owned post, so a
    // failed child delete cannot leave the database half-cleaned.
    $owned_post = mysqli_query(
        $conn,
        "SELECT id FROM posts WHERE id = $del_id AND author = '$me' LIMIT 1"
    );

    if ($owned_post && mysqli_num_rows($owned_post) === 1) {
        $has_image_blob_table = ensure_image_blob_table($conn);
        $delete_ok = true;

        mysqli_begin_transaction($conn);

        $dependent_queries = [
            "DELETE FROM chats WHERE item_id = $del_id",
            "DELETE FROM delivery_request WHERE item_id = $del_id"
        ];

        if ($has_image_blob_table) {
            $dependent_queries[] = "
                DELETE FROM swapy_image_blobs
                WHERE entity_type = 'post' AND entity_id = $del_id
            ";
        }

        $dependent_queries[] = "
            DELETE FROM posts
            WHERE id = $del_id AND author = '$me'
        ";

        foreach ($dependent_queries as $delete_query) {
            if (!mysqli_query($conn, $delete_query)) {
                $delete_ok = false;
                error_log(
                    'Swapy post deletion failed for post ' . $del_id . ': ' .
                    mysqli_error($conn)
                );
                break;
            }
        }

        if ($delete_ok) {
            mysqli_commit($conn);
            header("Location: profile.php?success=post_deleted");
        } else {
            mysqli_rollback($conn);
            header("Location: profile.php?error=failed_to_delete");
        }
    } else {
        header("Location: profile.php?error=post_not_found");
    }

